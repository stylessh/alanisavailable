#!/usr/bin/env node
// Moves a product on to its next version, keeping the one it's leaving:
//
//   node scripts/snapshot.mjs superlogical "Top bar"
//
// The live product always has a version name, in src/snapshots/<slug>/live.json
// (start one there by hand). This freezes the live product under that name,
// then names the live product "Top bar", for the work that comes next.
//
// The product folder, its public assets and the macOS layer it runs on are
// copied into src/snapshots/<slug>/v<n>/ (assets into public/snapshots/), with
// imports and asset paths pointed at the copies, so later work on the product
// or on src/os never changes an old version. Each version gets its own route
// file, src/app/v/<slug>/v<n>/, so a page bundles exactly one version's styles
// (versions share class names, and their styles must never meet). They live
// under /v rather than /<slug>: a static <slug> folder would shadow the
// product's own [slug] route. The
// registry in src/snapshots/index.ts is then rebuilt from the snapshot folders.
//
// To rename a version, edit its snapshot.json (or live.json) and run with --index.
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const SNAPSHOTS = path.join(ROOT, "src/snapshots");
const CODE = /\.(tsx?|mdx|css)$/;

const [slug, next] = process.argv.slice(2);
if (slug === "--index") {
  writeIndex();
  process.exit(0);
}
if (!slug || !next) {
  console.error('usage: node scripts/snapshot.mjs <slug> "<next version name>"\n       node scripts/snapshot.mjs --index');
  process.exit(1);
}

const product = path.join(ROOT, "src/products", slug);
if (!fs.existsSync(product)) throw new Error(`No product at src/products/${slug}`);

const versions = path.join(SNAPSHOTS, slug);
const live = path.join(versions, "live.json");
if (!fs.existsSync(live)) throw new Error(`Name the live version first: src/snapshots/${slug}/live.json, {"name": "…"}`);
const { name } = JSON.parse(fs.readFileSync(live, "utf8"));
const taken = fs.existsSync(versions) ? fs.readdirSync(versions).filter((d) => /^v\d+$/.test(d)) : [];
const id = `v${Math.max(0, ...taken.map((d) => Number(d.slice(1)))) + 1}`;
const dest = path.join(versions, id);

fs.cpSync(product, dest, { recursive: true });
fs.cpSync(path.join(ROOT, "src/os/macos"), path.join(dest, "os/macos"), { recursive: true });
const assets = path.join(ROOT, "public/products", slug);
if (fs.existsSync(assets)) fs.cpSync(assets, path.join(ROOT, "public/snapshots", slug, id), { recursive: true });

for (const file of walk(dest).filter((f) => CODE.test(f))) {
  const before = fs.readFileSync(file, "utf8");
  let rel = path.relative(path.dirname(file), path.join(dest, "os/macos"));
  if (!rel.startsWith(".")) rel = `./${rel}`;
  const after = before
    .replaceAll('"@/os/macos"', JSON.stringify(rel))
    .replaceAll(`/products/${slug}/`, `/snapshots/${slug}/${id}/`);
  if (after !== before) fs.writeFileSync(file, after);
  const leftover = after.match(/from ["']@\/[^"']+["']/);
  if (leftover) console.warn(`warning: ${path.relative(ROOT, file)} still imports ${leftover[0].slice(5)}, which isn't frozen`);
}

const commit = execSync("git rev-parse --short HEAD", { cwd: ROOT }).toString().trim();
const date = new Date().toISOString().slice(0, 10);
fs.writeFileSync(path.join(dest, "snapshot.json"), `${JSON.stringify({ name, date, commit }, null, 2)}\n`);
fs.writeFileSync(live, `${JSON.stringify({ name: next }, null, 2)}\n`);
writeIndex();
console.log(`froze "${name}" as ${slug}/${id}; the live product is now "${next}"`);

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)],
  );
}

// Each version's route, so a page bundles exactly one version's styles.
function writeRoute(slug, id) {
  const route = path.join(ROOT, "src/app/v", slug, id);
  fs.mkdirSync(route, { recursive: true });
  fs.writeFileSync(
    path.join(route, "page.tsx"),
    `// Generated by scripts/snapshot.mjs: ${slug} as it was at ${id}.
import { SnapshotPage, snapshotMetadata } from "@/components/snapshot-page";
import Content from "@/snapshots/${slug}/${id}/index.mdx";

export const generateMetadata = () => snapshotMetadata(${JSON.stringify(slug)}, ${JSON.stringify(id)});

export default function Page() {
  return (
    <SnapshotPage slug=${JSON.stringify(slug)} id=${JSON.stringify(id)}>
      <Content />
    </SnapshotPage>
  );
}
`,
  );
}

function writeIndex() {
  const slugs = fs.existsSync(SNAPSHOTS)
    ? fs.readdirSync(SNAPSHOTS, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort()
    : [];
  const entries = slugs.map((s) => {
    const ids = fs
      .readdirSync(path.join(SNAPSHOTS, s))
      .filter((d) => /^v\d+$/.test(d))
      .sort((a, b) => Number(a.slice(1)) - Number(b.slice(1)));
    const items = ids.map((v) => {
      writeRoute(s, v);
      const { name, date, commit } = JSON.parse(fs.readFileSync(path.join(SNAPSHOTS, s, v, "snapshot.json"), "utf8"));
      return `      ${JSON.stringify({ id: v, name, date, commit })},`;
    });
    const live = JSON.parse(fs.readFileSync(path.join(SNAPSHOTS, s, "live.json"), "utf8")).name;
    return `  ${JSON.stringify(s)}: {\n    live: ${JSON.stringify(live)},\n    snapshots: [${items.length ? `\n${items.join("\n")}\n    ` : ""}],\n  },`;
  });
  fs.mkdirSync(SNAPSHOTS, { recursive: true });
  fs.writeFileSync(
    path.join(SNAPSHOTS, "index.ts"),
    `// Generated by scripts/snapshot.mjs from the snapshot folders; rerun it with
// --index after editing a snapshot.json or live.json instead of editing this file.
//
// Names only: importing a version's code here would put its styles on every
// page that reads this list. Each version's code is imported by its own route.
import type { Snapshot } from "@/lib/snapshots";

export const VERSIONS: Record<string, { live: string; snapshots: Snapshot[] }> = {
${entries.join("\n")}
};
`,
  );
}
